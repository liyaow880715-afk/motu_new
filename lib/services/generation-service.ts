async function promoteSectionAsToneAnchor(projectId: string, sectionId: string, imageAsset: ProductAsset) {
  const project = await prisma.project.findUnique({
    where: { id: projectId },
    select: { modelSnapshot: true },
  });
  if (!project) return;

  const snapshot = (project.modelSnapshot as Record<string, unknown> | null) ?? {};
  const styleGuide = (snapshot.styleGuide as Record<string, unknown> | null) ?? {};
  const assetMetadata = (imageAsset.metadata as Record<string, unknown> | null) ?? {};
  const approvedAt = new Date().toISOString();
  await prisma.$transaction([
    prisma.productAsset.update({
      where: { id: imageAsset.id },
      data: {
        metadata: {
          ...assetMetadata,
          kind: "approved_section_tone_anchor_v1",
          toneAnchorApprovedAt: approvedAt,
        } as Prisma.InputJsonValue,
      },
    }),
    prisma.project.update({
      where: { id: projectId },
      data: {
        modelSnapshot: {
          ...snapshot,
          styleGuide: {
            ...styleGuide,
            anchorKind: "approved_section_tone_anchor_v1",
            anchorImageAssetId: imageAsset.id,
            anchorSectionId: sectionId,
            anchorApprovedAt: approvedAt,
          },
        } as Prisma.InputJsonValue,
      },
    }),
  ]);
}

async function getAdjacentSections(projectId: string, currentSectionId: string, includeImages = true) {
  const sections = await prisma.pageSection.findMany({
    where: { projectId },
    orderBy: { order: "asc" },
    select: { id: true, type: true, title: true, goal: true, currentImageAssetId: true },
  });

  const index = sections.findIndex((s) => s.id === currentSectionId);
  if (index === -1) return [];

  const neighborSections = [
    index > 0 ? sections[index - 1] : null,
    index < sections.length - 1 ? sections[index + 1] : null,
  ].filter((s): s is NonNullable<typeof s> => s !== null);

  const assetIds = includeImages
    ? neighborSections
        .map((s) => s.currentImageAssetId)
        .filter((id): id is string => Boolean(id))
    : [];
  const assets = assetIds.length
    ? await prisma.productAsset.findMany({ where: { id: { in: assetIds } } })
    : [];
  const assetById = new Map(assets.map((asset) => [asset.id, asset]));

  const adjacent: Array<{
    type: string;
    title: string;
    goal: string;
    imageUrl?: string;
    imageAsset?: AssetRecord;
  }> = [];
  for (const neighbor of neighborSections) {
    const asset = neighbor.currentImageAssetId ? assetById.get(neighbor.currentImageAssetId) : null;
    const imageUrl = includeImages && asset ? await assetToDataUrl(asset) : undefined;
    adjacent.push({
      type: neighbor.type,
      title: neighbor.title,
      goal: neighbor.goal,
      imageUrl,
      imageAsset: asset ?? undefined,
    });
  }

  return adjacent;
}

function getSectionAspectRatio(
  section: Pick<PageSection, "type" | "editableData">,
  detailAspectRatio: "3:4" | "9:16",
): SectionImageAspectRatio {
  if (section.type === "HERO") return "1:1";

  // Optional modules (e.g. 成分配料表 / 白底商品图 / 规格图) can pin their own ratio.
  const controls = ((section.editableData as Record<string, unknown> | null) ?? {}).controls as
    | Record<string, unknown>
    | undefined;
  const pinned = controls?.aspectRatio;
  if (pinned === "1:1" || pinned === "3:4" || pinned === "9:16") {
    return pinned;
  }

  return detailAspectRatio;
}

function getOutputSize(aspectRatio: SectionImageAspectRatio) {
  if (aspectRatio === "1:1") {
    return "1024x1024";
  }

  if (aspectRatio === "3:4") {
    return "768x1024";
  }

  return "1024x1536";
}

function isStableImageModel(modelId: string) {
  return !/(preview|experimental|beta|test)/i.test(modelId);
}

function isPreferredImageModel(modelId: string) {
  return /(banana|nano-banana|nano banana|imagen|recraft|flux|gemini|gpt-image|gpt-image-1)/i.test(modelId);
}

function isGeminiImageModel(modelId: string) {
  return /gemini.*image|nano-banana|banana/i.test(modelId);
}

function readCapabilities(model: { capabilities: unknown }) {
  return (model.capabilities as Record<string, boolean> | null) ?? {};
}

function hasImageCapability(model: { capabilities: unknown }) {
  return Boolean(readCapabilities(model).image_gen);
}

function hasTextCapability(model: { capabilities: unknown }) {
  return Boolean(readCapabilities(model).text);
}

function hasVisionCapability(model: { capabilities: unknown }) {
  return Boolean(readCapabilities(model).vision);
}

function hasRealImageGeneration(model: { capabilities: unknown }) {
  return readCapabilities(model).real_image_gen !== false;
}

function hasRealImageEdit(model: { capabilities: unknown }) {
  return readCapabilities(model).real_image_edit !== false;
}

function canGenerateRealImage(model: { capabilities: unknown }) {
  return hasImageCapability(model) && (hasRealImageGeneration(model) || isGeminiImageModel((model as { modelId?: string }).modelId ?? ""));
}

function canEditRealImage(model: { capabilities: unknown }) {
  const capabilities = readCapabilities(model);
  return (
    (Boolean(capabilities.image_edit) && capabilities.real_image_edit !== false) ||
    (Boolean(capabilities.image_gen) &&
      (capabilities.real_image_gen !== false || isGeminiImageModel((model as { modelId?: string }).modelId ?? "")))
  );
}

function buildImageModelCandidates(
  provider: ProviderContext,
  options?: {
    preferredModelId?: string | null;
    regenerate?: boolean;
    edit?: boolean;
    isHero?: boolean;
    strict?: boolean;
  },
) {
  const candidatePool = provider.models.filter((item) =>
    options?.edit ? canEditRealImage(item) : canGenerateRealImage(item),
  );

  const defaultKey = options?.edit
    ? "isDefaultImageEdit"
    : options?.regenerate
      ? "isDefaultDetailImage"
      : options?.isHero
        ? "isDefaultHeroImage"
        : "isDefaultDetailImage";

  if (options?.strict) {
    const strictModel = options.preferredModelId ?? candidatePool.find((item) => Boolean(item[defaultKey]))?.modelId ?? null;
    return strictModel ? [strictModel] : [];
  }

  const candidates = [
    options?.preferredModelId ?? null,
    candidatePool.find((item) => Boolean(item[defaultKey]))?.modelId ?? null,
    candidatePool.find((item) => item.isDefaultDetailImage)?.modelId ?? null,
    ...candidatePool
      .filter((item) => isStableImageModel(item.modelId) && isPreferredImageModel(item.modelId))
      .map((item) => item.modelId),
    ...candidatePool.filter((item) => isStableImageModel(item.modelId)).map((item) => item.modelId),
    ...candidatePool.filter((item) => isPreferredImageModel(item.modelId)).map((item) => item.modelId),
    ...candidatePool.map((item) => item.modelId),
  ].filter(Boolean) as string[];

  return [...new Set(candidates)];
}

function buildSvgModelCandidates(provider: ProviderContext) {
  const visionText = provider.models.filter((item) => hasTextCapability(item) && hasVisionCapability(item));
  const textOnly = provider.models.filter((item) => hasTextCapability(item));

  const candidates = [
    provider.models.find((item) => item.isDefaultPlanning)?.modelId ?? null,
    provider.models.find((item) => item.isDefaultAnalysis)?.modelId ?? null,
    ...visionText
      .filter((item) => /gemini|gpt-4o|gpt-5/i.test(item.modelId) && !/preview|experimental|beta|test/i.test(item.modelId))
      .map((item) => item.modelId),
    ...visionText.filter((item) => !/preview|experimental|beta|test/i.test(item.modelId)).map((item) => item.modelId),
    ...textOnly
      .filter((item) => /gemini|gpt-4o|gpt-5/i.test(item.modelId) && !/preview|experimental|beta|test/i.test(item.modelId))
      .map((item) => item.modelId),
    ...textOnly.filter((item) => !/preview|experimental|beta|test/i.test(item.modelId)).map((item) => item.modelId),
    ...textOnly.map((item) => item.modelId),
  ].filter(Boolean) as string[];

  return [...new Set(candidates)];
}

function shouldFallbackToNextImageModel(error: unknown) {
  if (!(error instanceof Error)) {
    return false;
  }

  if (/429|rate limit|限流|timed out|timeout|abort|network|fetch failed|provider request failed \(5\d\d\)/i.test(error.message)) {
    return false;
  }
  return /404|405|no available endpoint|unsupported|not implemented|does not exist|invalid_value|returned no inline image data|unknown parameter|invalid type/i.test(
    error.message,
  );
}

function summarizeProviderImageFailure(detail: string, mode: "generate" | "edit") {
  const reasons: string[] = [];

  if (/model.+does not exist|invalid_value.+model/i.test(detail)) {
    reasons.push("代理商返回的图片模型名称无效或并不存在");
  }
  if (/no available endpoint|404/i.test(detail)) {
    reasons.push("代理商没有为这些模型开放真实图片端点");
  }
  if (/429|限流|rate limit/i.test(detail)) {
    reasons.push("代理商图片接口当前触发了限流");
  }
  if (/unknown parameter|invalid type|images\[0\]|supported values|invalid value.+size/i.test(detail)) {
    reasons.push("代理商图片接口的兼容格式与当前网关实现不一致");
  }

  if (!reasons.length) {
    reasons.push(mode === "edit" ? "图像编辑接口暂时不可用" : "图像生成接口暂时不可用");
  }

  return [...new Set(reasons)].join("；");
}

function extractJsonBlock(raw: string) {
  const direct = raw.trim();
  if (direct.startsWith("{") || direct.startsWith("[")) {
    return direct;
  }

  const fencedMatch = direct.match(/```json([\s\S]*?)```/i) || direct.match(/```([\s\S]*?)```/i);
  if (fencedMatch?.[1]) {
    return fencedMatch[1].trim();
  }

  const firstBrace = direct.indexOf("{");
  const lastBrace = direct.lastIndexOf("}");
  if (firstBrace >= 0 && lastBrace > firstBrace) {
    return direct.slice(firstBrace, lastBrace + 1);
  }

  return direct;
}

function escapeXml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

async function urlToDataUrl(imageUrl: string): Promise<string | null> {
  try {
    if (imageUrl.startsWith("data:")) {
      return imageUrl;
    }
    if (imageUrl.startsWith("http://") || imageUrl.startsWith("https://")) {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 15000);
      try {
        const res = await fetch(imageUrl, { signal: controller.signal });
        clearTimeout(timeout);
        if (!res.ok) return null;
        const buffer = Buffer.from(await res.arrayBuffer());
        const mimeType = res.headers.get("content-type") ?? "image/png";
        return `data:${mimeType};base64,${buffer.toString("base64")}`;
      } catch {
        clearTimeout(timeout);
        return null;
      }
    }
    // Local file path
    const filePath = imageUrl.startsWith("/") ? imageUrl.slice(1) : imageUrl;
    const buffer = await readStorageFile(filePath);
    const ext = filePath.split(".").pop()?.toLowerCase() ?? "png";
    const mimeType = ext === "jpg" || ext === "jpeg" ? "image/jpeg" : ext === "webp" ? "image/webp" : "image/png";
    return `data:${mimeType};base64,${buffer.toString("base64")}`;
  } catch (error) {
    console.error("[urlToDataUrl] Failed to convert URL to data URL:", imageUrl, error);
    return null;
  }
}

function readProductFacts(project: { analysis?: { normalizedResult?: unknown } | null } | null): ProductFacts | undefined {
  const result = (project?.analysis?.normalizedResult ?? undefined) as Record<string, unknown> | undefined;
  if (!result) return undefined;

  return {
    category: typeof result.category === "string" ? result.category : undefined,
    subcategory: typeof result.subcategory === "string" ? result.subcategory : undefined,
    coreSellingPoints: Array.isArray(result.coreSellingPoints)
      ? result.coreSellingPoints.filter((item): item is string => typeof item === "string")
      : undefined,
    factClaims: Array.isArray(result.factClaims)
      ? result.factClaims.flatMap((item) => {
          if (!item || typeof item !== "object") return [];
          const claim = item as Record<string, unknown>;
          const source = claim.source;
          const confidence = claim.confidence;
          if (
            typeof claim.claim !== "string" ||
            !["visible_image", "user_input", "structured_data", "analysis_inference"].includes(String(source)) ||
            !["high", "medium", "low"].includes(String(confidence))
          ) {
            return [];
          }
          return [{
            claim: claim.claim,
            source: source as "visible_image" | "user_input" | "structured_data" | "analysis_inference",
            evidence: typeof claim.evidence === "string" ? claim.evidence : undefined,
            confidence: confidence as "high" | "medium" | "low",
            confirmed: claim.confirmed === true,
            eligibleForMarketing: claim.eligibleForMarketing === true,
          }];
        })
      : undefined,
    nutritionFacts:
      typeof result.nutritionFacts === "object" && result.nutritionFacts !== null
        ? (result.nutritionFacts as Record<string, string>)
        : undefined,
    ingredients: Array.isArray(result.ingredients)
      ? result.ingredients.map((item) => (typeof item === "string" ? item : String(item))).filter(Boolean)
      : undefined,
    specs: Array.isArray(result.specs)
      ? result.specs
          .filter((item): item is Record<string, unknown> => typeof item === "object" && item !== null)
          .filter((item) => typeof item.label === "string" && typeof item.value === "string")
          .map((item) => ({ label: item.label as string, value: item.value as string }))
      : undefined,
    packagingDescription: typeof result.packagingDescription === "string" ? result.packagingDescription : undefined,
  };
}

