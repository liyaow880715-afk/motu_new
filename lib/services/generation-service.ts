export async function editSectionImage(
  projectId: string,
  sectionId: string,
  options?: {
    preferredModelId?: string | null;
    referenceAssetIds?: string[];
    editMode?: "repaint" | "enhance";
    idempotencyKey?: string | null;
  },
) {
  const project = await prisma.project.findUnique({
    where: { id: projectId },
    include: {
      assets: { orderBy: [{ isMain: "desc" }, { sortOrder: "asc" }, { createdAt: "asc" }] },
      analysis: true,
      variants: { orderBy: { sortOrder: "asc" } },
    },
  });

  const section = await prisma.pageSection.findUnique({
    where: { id: sectionId },
    include: {
      currentImageAsset: true,
    },
  });

  if (!project) {
    throw new Error("Project not found.");
  }

  if (!section || section.projectId !== projectId) {
    throw new Error("Section not found.");
  }

  if (!section.currentImageAsset) {
    throw new Error("当前模块还没有可编辑的底图，请先生成一张模块图。");
  }

  const editableData = (section.editableData ?? {}) as Record<string, unknown>;
  const isLifestyleScene = isLifestyleSceneSection(
    section.type,
    editableData.visualMode,
    `${section.title} ${section.goal} ${section.visualPrompt}`,
  );
  const variantScope = editableData.variantScope as "base" | "variant" | "group" | undefined;
  const variantId = editableData.variantId as string | undefined;
  const variantIds = editableData.variantIds as string[] | undefined;
  const groupLayout = editableData.groupLayout as "row" | "triangle" | "scene" | undefined;

  const variantContext =
    variantScope === "variant" && variantId
      ? (() => {
          const variant = project.variants?.find((v) => v.id === variantId);
          const metadata = (variant?.metadata ?? {}) as Record<string, unknown>;
          const analysis =
            typeof metadata.analysis === "object" && metadata.analysis !== null
              ? (metadata.analysis as Record<string, unknown>)
              : {};
          return {
            scope: "variant" as const,
            variantId,
            variantName: variant?.name ?? "",
            description: typeof analysis.description === "string" ? analysis.description : undefined,
            keyIngredients: Array.isArray(analysis.keyIngredients) ? (analysis.keyIngredients as string[]) : undefined,
            packagingNotes: typeof analysis.packagingNotes === "string" ? analysis.packagingNotes : undefined,
            differences: typeof analysis.differences === "string" ? analysis.differences : undefined,
          };
        })()
      : variantScope === "group" && variantIds && variantIds.length > 0
        ? {
            scope: "group" as const,
            variantIds,
            layout: groupLayout,
            variants: variantIds
              .map((id) => project.variants?.find((v) => v.id === id))
              .filter(Boolean)
              .map((variant) => {
                const metadata = (variant?.metadata ?? {}) as Record<string, unknown>;
                const analysis =
                  typeof metadata.analysis === "object" && metadata.analysis !== null
                    ? (metadata.analysis as Record<string, unknown>)
                    : {};
                return {
                  variantId: variant!.id,
                  variantName: variant!.name,
                  description: typeof analysis.description === "string" ? analysis.description : undefined,
                };
              }),
          }
        : { scope: "base" as const };

  const { provider, adapter } = await getProviderAdapter("image");
  const generationSettings = getGenerationSettings(project);
  const sectionAspectRatio = getSectionAspectRatio(section, generationSettings.imageAspectRatio);
  const outputSize = getOutputSize(sectionAspectRatio);
  const modelCandidates = buildImageModelCandidates(provider, {
    preferredModelId: options?.preferredModelId,
    edit: true,
    regenerate: true,
    strict: generationSettings.strictImageModel,
  });
  const selectedModel = modelCandidates[0] ?? null;
  const explicitReferenceAssets = await resolveReferenceAssets(options?.referenceAssetIds ?? []);
  const sectionReferenceAssetIds = ((section.editableData as Record<string, unknown> | null)?.referenceAssetIds as string[] | undefined) ?? [];
  const sectionReferenceAssets = await resolveReferenceAssets(sectionReferenceAssetIds);
  const allExplicitAssets = [...sectionReferenceAssets, ...explicitReferenceAssets];
  const editReferenceResolution = resolveSectionReferenceAssets({
    section,
    projectAssets: project.assets as AssetRecord[],
    explicitReferenceAssets: allExplicitAssets as AssetRecord[],
  });
  const editIncludePackaging = editReferenceResolution.includePackaging;
  const editEffectiveReferenceAssets = editReferenceResolution.effectiveReferenceAssets;
  const editImageReferenceAssets = editReferenceResolution.modelProductAssets;
  const editAuthoritativeCrossSectionAssetIds = editReferenceResolution.authoritativeCrossSectionAssetIds;
  const editCrossSectionRequested = sectionRequestsCrossSection(section);
  const editProductFacts = readProductFacts(project);
  const baseImage = await assetToDataUrl(section.currentImageAsset as AssetRecord);
  const editReferenceAssets = editImageReferenceAssets.filter((asset) => asset.id !== section.currentImageAssetId);
  const editMode = options?.editMode ?? "repaint";
  const runningTask = await findRecentRunningTask({
    projectId,
    sectionId,
    taskType: "REGENERATE",
    maxAgeMinutes: 20,
  });
  if (runningTask) {
    throw new Error("当前模块图仍在重绘或增强中，请等待这一轮完成后再试。");
  }

  const task = await createTask({
    projectId,
    sectionId,
    taskType: "REGENERATE",
    idempotencyKey: options?.idempotencyKey,
    inputPayload: {
      mode: "edit_image",
      editMode,
      model: selectedModel,
      modelCandidates,
      baseImageAssetId: section.currentImageAssetId,
      referenceAssetIds: options?.referenceAssetIds ?? [],
      effectiveReferenceAssetIds: editEffectiveReferenceAssets.map((asset) => asset.id),
      authoritativeCrossSectionAssetIds: editAuthoritativeCrossSectionAssetIds,
      visualMode: isLifestyleScene ? "lifestyle_scene" : editableData.visualMode ?? "poster",
      allowSvgFallback: generationSettings.allowSvgFallback,
    },
  });

  await prisma.pageSection.update({
    where: { id: sectionId },
    data: { status: "GENERATING" },
  });

  const editStyleGuide = readProjectStyleGuide(project);
  const editAdjacentSections = await getAdjacentSections(projectId, sectionId, false);
  const editStyleAnchorReference = section.order === 0 ? null : await resolveStyleAnchorReference(projectId);
  const editStyleAnchorDataUrl = editStyleAnchorReference?.dataUrl ?? null;
  if (section.order > 0 && !editStyleAnchorDataUrl) {
    throw new Error("请先生成并通过首张头图的质量审核，以建立整页色调锚点，再编辑其他模块。");
  }
  const editIncludedProductAssets = editReferenceAssets.slice(
    0,
    Math.max(0, MAX_MODEL_REFERENCE_IMAGES - (editStyleAnchorDataUrl ? 1 : 0)),
  );
  const editProviderReferenceInputs = [
    ...editIncludedProductAssets.map((asset) => ({
      key: `asset:${asset.id}`,
      role: "product" as const,
      assetId: asset.id,
      fileName: asset.fileName,
      type: asset.type,
      url: null,
    })),
    ...(editStyleAnchorReference
      ? [{
          key: editStyleAnchorReference.asset
            ? `asset:${editStyleAnchorReference.asset.id}`
            : `style:${editStyleAnchorReference.sourceUrl ?? "approved"}`,
          role: "style_anchor" as const,
          assetId: editStyleAnchorReference.asset?.id ?? null,
          fileName: editStyleAnchorReference.asset?.fileName ?? "style-anchor",
          type: editStyleAnchorReference.asset?.type ?? "REFERENCE",
          url: editStyleAnchorReference.sourceUrl,
        }]
      : []),
  ];

  try {
    let prompt = buildImageEditPrompt(
      section,
      editImageReferenceAssets as ProductAsset[],
      editMode,
      sectionAspectRatio,
      generationSettings.contentLanguage,
      editStyleGuide,
      editAdjacentSections,
      editProductFacts,
      editIncludePackaging,
      variantContext,
      project.platform,
    );

    let imageAsset: ProductAsset;
    let version;
    let usedModel: string;
    let generationMode: "image_api" | "svg_fallback";

    try {
      if (!selectedModel) {
        throw new Error("当前 Provider 没有探测到可用于真实图片编辑的模型。");
      }

      const editReferenceImages = await buildReferenceImageList({
        productReferenceAssets: editReferenceAssets,
        styleAnchorDataUrl: editStyleAnchorDataUrl,
        templateReferenceImageDataUrl: null,
        neighborImageDataUrls: [],
      });

      const editIncludedProductCount = editIncludedProductAssets.length;
      prompt += buildReferenceImageInstruction({
        productReferenceAssets: editReferenceAssets.slice(0, editIncludedProductCount),
        authoritativeCrossSectionAssetIds: editAuthoritativeCrossSectionAssetIds,
        styleAnchorDataUrl: editStyleAnchorDataUrl,
        templateReferenceImageDataUrl: null,
        neighborImageCount: 0,
        sectionType: section.type,
        crossSectionRequested: editCrossSectionRequested,
      });

      const generation = await editWithFallback({
        adapter,
        candidateModels: modelCandidates,
        prompt,
        image: baseImage,
        size: outputSize,
        aspectRatio: sectionAspectRatio,
        referenceImages: editReferenceImages,
        projectId,
        sectionId,
        operation: editMode === "enhance" ? "enhance_section_image" : "repaint_section_image",
        strict: generationSettings.strictImageModel,
        idempotencyKey: options?.idempotencyKey,
      });

      imageAsset = await saveGeneratedImage({
        projectId,
        sectionId,
        prompt,
        source: generation.generated,
        metadata: {
          mode: "image_api",
          usedModel: generation.model,
          editMode,
          baseImageAssetId: section.currentImageAssetId,
          sourceReferenceAssetIds: editProviderReferenceInputs
            .map((input) => input.assetId)
            .filter((assetId): assetId is string => Boolean(assetId)),
          providerReferenceInputs: editProviderReferenceInputs,
          providerReferenceCount: editProviderReferenceInputs.length,
          authoritativeCrossSectionAssetIds: editAuthoritativeCrossSectionAssetIds,
          primaryReferenceAssetId: editIncludedProductAssets[0]?.id ?? null,
          visualMode: isLifestyleScene ? "lifestyle_scene" : editableData.visualMode ?? "poster",
          aspectRatio: sectionAspectRatio,
        },
      });

      usedModel = generation.model;
      generationMode = "image_api";
    } catch (error) {
      if (!generationSettings.allowSvgFallback) {
        const detail = error instanceof Error ? error.message : "Unknown image edit error";
        if (/monthly spending limit|spending limit|billing|quota/i.test(detail)) {
          throw new Error("当前 API Key 的图片编辑/生成额度已用尽。请前往代理商控制台提高或移除月度限额，或更换可用的 API Key。");
        }
        const summary = summarizeProviderImageFailure(detail, "edit");
        throw new Error(
          `当前 Provider 没有可用的真实图片生成或编辑端点。请前往“模型服务配置”页更换支持图片编辑的 Provider，或在规划页手动开启“允许 SVG 兜底预览”。原因摘要：${summary}`,
        );
      }

      const fallback = await generateSvgFallback({
        section,
        adapter,
        provider,
        referenceAssets: editImageReferenceAssets,
        aspectRatio: sectionAspectRatio,
        contentLanguage: generationSettings.contentLanguage,
        styleGuide: editStyleGuide,
      });

      const editSvgBuffer = await generationResultToBuffer({
        svgText: fallback.svgText,
        mimeType: "image/svg+xml",
      });

      imageAsset = await saveGeneratedImage({
        projectId,
        sectionId,
        prompt,
        source: {
          b64Json: editSvgBuffer.toString("base64"),
          mimeType: "image/png",
        },
        metadata: {
          mode: "svg_fallback",
          usedModel: fallback.model,
          editMode,
          baseImageAssetId: section.currentImageAssetId,
          layout: fallback.layout,
          sourceReferenceAssetIds: editProviderReferenceInputs
            .map((input) => input.assetId)
            .filter((assetId): assetId is string => Boolean(assetId)),
          providerReferenceInputs: editProviderReferenceInputs,
          providerReferenceCount: editProviderReferenceInputs.length,
          primaryReferenceAssetId: editIncludedProductAssets[0]?.id ?? null,
          compositedPackaging: false,
          imageApiError: error instanceof Error ? error.message : "Unknown image edit api error",
          aspectRatio: sectionAspectRatio,
        },
      });

      usedModel = fallback.model;
      generationMode = "svg_fallback";
    }

    version = await persistSectionVersion({
      sectionId,
      imageAssetId: imageAsset.id,
      promptSnapshot: prompt,
      copySnapshot: section.copy,
    });

    await prisma.pageSection.update({
      where: { id: sectionId },
      data: {
        status: "REVIEW",
        currentImageAssetId: imageAsset.id,
      },
    });

    let qualityScore: Awaited<ReturnType<typeof scoreGeneratedImage>> | null = null;
    let qualityGate: ReturnType<typeof assessGeneratedAssetQualityGate> & { scoringError?: string };
    try {
      qualityScore = await scoreGeneratedImage(imageAsset.id, { force: true });
      qualityGate = assessGeneratedAssetQualityGate(qualityScore, {
        requiresPackaging: editIncludePackaging,
        generationMode,
      });
    } catch (scoreError) {
      const scoringError = scoreError instanceof Error ? scoreError.message : "图片质量评分失败";
      console.error("[ImageQualityScore] Failed to score edited image:", imageAsset.id, scoreError);
      qualityGate = {
        passed: false,
        failed: [],
        constraints: ["质量评分未完成"],
        summary: `质量评分未完成：${scoringError}`,
        scoringError,
      };
    }

    imageAsset = await prisma.productAsset.update({
      where: { id: imageAsset.id },
      data: {
        metadata: {
          ...((imageAsset.metadata as Record<string, unknown> | null) ?? {}),
          qualityGate: {
            passed: qualityGate.passed,
            summary: qualityGate.summary,
            failed: qualityGate.failed,
            constraints: qualityGate.constraints,
            scoreId: qualityScore?.id ?? null,
            scoredAt: qualityScore?.scoredAt?.toISOString() ?? null,
          },
        } as Prisma.InputJsonValue,
      },
    });
    if (qualityGate.passed && section.order === 0 && section.type === "HERO") {
      await promoteSectionAsToneAnchor(projectId, sectionId, imageAsset);
    }
    await prisma.pageSection.update({
      where: { id: sectionId },
      data: { status: qualityGate.passed ? "SUCCESS" : "REVIEW" },
    });

    await prisma.project.update({
      where: { id: projectId },
      data: {
        status: "EDITING",
      },
    });

    await completeTask(task.id, {
      mode: "edit_image",
      editMode,
      imageAssetId: imageAsset.id,
      versionId: version.id,
      usedModel,
      generationMode,
      baseImageAssetId: section.currentImageAssetId,
      sourceReferenceAssetIds: editProviderReferenceInputs
        .map((input) => input.assetId)
        .filter((assetId): assetId is string => Boolean(assetId)),
      providerReferenceInputs: editProviderReferenceInputs,
      qualityScoreId: qualityScore?.id ?? null,
      qualityGate,
    });

    return { imageAsset, version, usedModel, generationMode, editMode, qualityScore, qualityGate };
  } catch (error) {
    await prisma.pageSection.update({
      where: { id: sectionId },
      data: {
        status: "FAILED",
      },
    });

    await failTask(task.id, error instanceof Error ? error.message : "Image edit failed");
    throw error;
  }
}

