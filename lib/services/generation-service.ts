async function generateWithFallback(params: {
  adapter: AdapterContext;
  candidateModels: string[];
  prompt: string;
  size: string;
  aspectRatio: SectionImageAspectRatio;
  referenceImages: string[];
  projectId: string;
  sectionId: string;
  operation: string;
  strict?: boolean;
  idempotencyKey?: string | null;
}) {
  const errors: string[] = [];
  const maxAttempts = params.strict ? 1 : MAX_IMAGE_GENERATION_FALLBACKS;

  for (const model of params.candidateModels.slice(0, maxAttempts)) {
    try {
      const generated = await params.adapter.generateImage({
        model,
        prompt: params.prompt,
        size: params.size,
        aspectRatio: params.aspectRatio,
        referenceImages: params.referenceImages,
        idempotencyKey: params.idempotencyKey ?? undefined,
        timeoutMs: 360_000,
        monitor: {
          projectId: params.projectId,
          sectionId: params.sectionId,
          operation: params.operation,
        },
      });

      return {
        model,
        generated,
        attemptedModels: params.candidateModels,
      };
    } catch (error) {
      const message = error instanceof Error ? error.message : "Unknown image generation error";
      errors.push(`${model}: ${message}`);

      if (params.strict) {
        throw new Error(`严格模式下模型 ${model} 生成失败，未启用自动降级：${message}`);
      }

      if (!shouldFallbackToNextImageModel(error)) {
        throw error;
      }
    }
  }

  throw new Error(`所有可用图片模型都生成失败：${errors.join(" | ")}`);
}

function selectGroupReferenceAssets(
  variantIds: string[],
  assetPool: AssetRecord[],
  fallbackPool: AssetRecord[] = [],
): AssetRecord[] {
  const selected: AssetRecord[] = [];
  for (const variantId of variantIds) {
    const variantAssets = assetPool.filter((asset) => asset.variantId === variantId);
    const pick =
      variantAssets.find((asset) => asset.type === "PACKAGING") ??
      variantAssets.find((asset) => asset.type === "MAIN") ??
      variantAssets.find((asset) => ["ANGLE", "DETAIL"].includes(asset.type));
    if (pick) {
      selected.push(pick);
      continue;
    }
    // If this variant has no dedicated images, fall back to common/base product images.
    const fallback =
      fallbackPool.find((asset) => asset.type === "MAIN") ??
      fallbackPool.find((asset) => ["ANGLE", "DETAIL"].includes(asset.type)) ??
      fallbackPool.find((asset) => asset.type === "PACKAGING");
    if (fallback) selected.push(fallback);
  }
  return selected.slice(0, MAX_MODEL_REFERENCE_IMAGES);
}

async function generateGroupImageOneShot(params: {
  section: PageSection;
  variantContext: Extract<VariantContext, { scope: "group" }>;
  assetPool: AssetRecord[];
  referenceAssets: AssetRecord[];
  styleAnchorDataUrl: string | null;
  authoritativeCrossSectionAssetIds: string[];
  adapter: AdapterContext;
  candidateModels: string[];
  sectionAspectRatio: SectionImageAspectRatio;
  outputSize: string;
  contentLanguage: ContentLanguage;
  styleGuide?: StyleGuide;
  adjacentSections?: any[];
  productFacts?: ProductFacts;
  includePackaging: boolean;
  platform?: string;
  projectId: string;
  sectionId: string;
  strict: boolean;
  operation: string;
  idempotencyKey?: string | null;
}) {
  const missingVariantNames = params.variantContext.variants
    .filter((variant) => !params.assetPool.some((asset) => asset.variantId === variant.variantId))
    .map((variant) => variant.variantName);
  if (missingVariantNames.length > 0) {
    throw new Error(
      `组合图生成失败，以下规格缺少专属参考图：${missingVariantNames.join("、")}。请为每个规格上传至少 1 张包装图或产品图。`,
    );
  }

  const groupReferenceAssets = params.referenceAssets.slice(
    0,
    Math.max(1, MAX_MODEL_REFERENCE_IMAGES - (params.styleAnchorDataUrl ? 1 : 0)),
  );
  const referenceImageDataUrls = await Promise.all(
    groupReferenceAssets.map((asset) => assetToDataUrl(asset).then((url) => resizeReferenceImageDataUrl(url))),
  );
  if (params.styleAnchorDataUrl) {
    referenceImageDataUrls.push(await resizeReferenceImageDataUrl(params.styleAnchorDataUrl));
  }

  const prompt = buildSectionImagePrompt(
    params.section,
    groupReferenceAssets as ProductAsset[],
    params.sectionAspectRatio,
    params.contentLanguage,
    params.styleGuide,
    params.adjacentSections,
    params.productFacts,
    params.includePackaging,
    params.variantContext,
    params.platform,
  );

  const instruction = buildReferenceImageInstruction({
    productReferenceAssets: groupReferenceAssets,
    authoritativeCrossSectionAssetIds: params.authoritativeCrossSectionAssetIds,
    styleAnchorDataUrl: params.styleAnchorDataUrl,
    templateReferenceImageDataUrl: null,
    neighborImageCount: 0,
    sectionType: params.section.type,
    crossSectionRequested: sectionRequestsCrossSection(params.section),
  });

  const positionMapping = groupReferenceAssets
    .map((asset, index) => {
      const variantIndex = params.variantContext.variants.findIndex((variant) => variant.variantId === asset.variantId);
      const variant = variantIndex >= 0 ? params.variantContext.variants[variantIndex] : null;
      return variant
        ? `Reference image ${index + 1} belongs to position ${variantIndex + 1}: "${variant.variantName}"; role=${asset.type}.`
        : `Reference image ${index + 1} is shared product evidence; role=${asset.type}.`;
    })
    .join("\n");
  const representedVariantIds = new Set(groupReferenceAssets.map((asset) => asset.variantId).filter(Boolean));
  const missingCount = params.variantContext.variants.filter(
    (variant) => !representedVariantIds.has(variant.variantId),
  ).length;
  const missingNote =
    missingCount > 0
      ? `\nNote: reference images are only provided for the first ${groupReferenceAssets.length} variant(s); render the remaining ${missingCount} variant(s) consistently with their descriptions and the provided examples.`
      : "";

  const generation = await generateWithFallback({
    adapter: params.adapter,
    candidateModels: params.candidateModels,
    prompt: `${prompt}\n\n${instruction}\n\n${positionMapping}${missingNote}`,
    size: params.outputSize,
    aspectRatio: params.sectionAspectRatio,
    referenceImages: referenceImageDataUrls,
    projectId: params.projectId,
    sectionId: params.sectionId,
    operation: params.operation,
    strict: params.strict,
    idempotencyKey: params.idempotencyKey,
  });

  return {
    generation,
    prompt,
  };
}

