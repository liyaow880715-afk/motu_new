function readProjectStyleGuide(project: { modelSnapshot: unknown } | null): StyleGuide | undefined {
  const snapshot = (project?.modelSnapshot as Record<string, unknown> | null) ?? {};
  const styleGuide = snapshot.styleGuide as Record<string, unknown> | undefined;
  if (!styleGuide) return undefined;

  const colorPalette = styleGuide.colorPalette as Record<string, string> | undefined;
  return {
    colorPalette: colorPalette
      ? {
          background: colorPalette.background,
          primary: colorPalette.primary,
          secondary: colorPalette.secondary,
          accent: colorPalette.accent,
          text: colorPalette.text,
        }
      : undefined,
    typography: styleGuide.typography as
      | { headingStyle?: string; bodyStyle?: string; headingFont?: string; bodyFont?: string }
      | undefined,
    mood: typeof styleGuide.mood === "string" ? styleGuide.mood : undefined,
    paletteStyle:
      snapshot.paletteStyle === "contrast" || snapshot.paletteStyle === "bold" ? snapshot.paletteStyle : "safe",
    visualSystem: styleGuide.visualSystem as StyleGuide["visualSystem"] | undefined,
  };
}

async function getExistingStyleAnchorReference(projectId: string): Promise<{
  asset: AssetRecord | null;
  dataUrl: string;
  sourceUrl: string | null;
} | null> {
  const project = await prisma.project.findUnique({
    where: { id: projectId },
    select: { modelSnapshot: true },
  });
  if (!project) return null;

  const snapshot = (project.modelSnapshot as Record<string, unknown> | null) ?? {};
  const styleGuide = snapshot.styleGuide as Record<string, unknown> | undefined;
  const anchorAssetId = typeof styleGuide?.anchorImageAssetId === "string" ? styleGuide.anchorImageAssetId : null;
  const anchorUrl = typeof styleGuide?.anchorImageUrl === "string" ? styleGuide.anchorImageUrl : null;
  const anchorKind = typeof styleGuide?.anchorKind === "string" ? styleGuide.anchorKind : null;

  if (anchorAssetId) {
    const asset = await prisma.productAsset.findUnique({ where: { id: anchorAssetId } });
    if (asset && anchorKind === "approved_section_tone_anchor_v1" && isApprovedToneAnchor(asset)) {
      return { asset, dataUrl: await assetToDataUrl(asset), sourceUrl: null };
    }
  }

  if (anchorUrl && anchorKind === "approved_section_tone_anchor_v1") {
    const dataUrl = await urlToDataUrl(anchorUrl);
    return dataUrl ? { asset: null, dataUrl, sourceUrl: anchorUrl } : null;
  }

  return null;
}

